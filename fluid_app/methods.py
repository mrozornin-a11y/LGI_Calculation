def translate_core_message(message: str) -> str:
    """Перевод сообщения ядра; неизвестные сообщения возвращаются без изменений."""
    return _CORE_MESSAGES_RU.get(str(message).strip(), str(message))


def kind_label(kind: str) -> str:
    return KINDS.get(kind, (kind, kind))[0]


def methods_html() -> str:
    """Справка по методикам, источникам и ограничениям (HTML для QTextBrowser)."""
    parts = ['<h2>Использованные методики и источники</h2>']
    for key, m in METHODS.items():
        parts.append(f'<h3>{m["title"]}</h3><table cellpadding="3">')
        for label, field in (('Входные данные', 'input'), ('Результат', 'output'),
                             ('Уравнение', 'equation'), ('Область применимости', 'range'),
                             ('Функция ядра', 'core_function'), ('Источник', 'citation')):
            parts.append(f'<tr><td valign="top"><b>{label}</b></td><td>{m[field]}</td></tr>')
        parts.append(f'<tr><td><b>DOI</b></td><td>https://doi.org/{m["doi"]}</td></tr></table>')
        parts.append('<p><b>Допущения:</b></p><ul>' + ''.join(f'<li>{a}</li>' for a in m['assumptions']) + '</ul>')
        parts.append('<p><b>Ограничения:</b></p><ul>' + ''.join(f'<li>{a}</li>' for a in m['limitations']) + '</ul>')
    parts.append('<h3>Наблюдения без расчёта</h3><ul>')
    for kind, reason in KIND_NO_CALC_REASON.items():
        parts.append(f'<li><b>{kind_label(kind)}</b>: {reason}</li>')
    parts.append('</ul><h2>Общие ограничения</h2><ul>')
    parts += [f'<li>{x}</li>' for x in GENERAL_LIMITATIONS]
    parts.append('</ul><h2>Не реализованные научные модели</h2><table border="1" cellspacing="0" cellpadding="4">'
                 '<tr><th>Модель</th><th>Назначение</th><th>DOI</th></tr>')
    for name, purpose, doi in NOT_IMPLEMENTED_MODELS:
        parts.append(f'<tr><td>{name}</td><td>{purpose}</td><td>{doi}</td></tr>')
    parts.append('</table><h2>Незавершённая научная проверка</h2><ol>')
    parts += [f'<li>{x}</li>' for x in PENDING_VALIDATION]
    parts.append('</ol>')
    return '\n'.join(parts)
