INTERPRETATION_STATUS_RU = 'интерпретация (не расчёт)'


def method_category(method_key: str | None) -> str:
    """Вид результата по ключу методики: 'calculation' или 'interpretation' ('observation' — методики нет)."""
    if not method_key:
        return 'observation'
    return METHODS.get(method_key, {}).get('category', 'calculation')


def status_label(status: str, method_key: str | None = None) -> str:
    """Подпись статуса строки результата; успешная интерпретация не называется «рассчитано»."""
    if status == 'ok' and method_category(method_key) == 'interpretation':
        return INTERPRETATION_STATUS_RU
    return STATUS_RU.get(status, status)

